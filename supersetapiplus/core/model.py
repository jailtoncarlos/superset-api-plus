"""Serialization of the models (no HTTP): SerializableModel and its JSON encoder."""
import dataclasses
import json
import logging
from abc import ABC
from collections.abc import Mapping
from enum import Enum
from pathlib import Path
from types import MappingProxyType
from typing import Any, cast, get_origin

from typing_extensions import Self

from supersetapiplus.core.dicts import dicts_equal_and_all_values_none
from supersetapiplus.core.masking import mask_data
from supersetapiplus.core.parse import ParseMixin
from supersetapiplus.core.sentinels import MissingField
from supersetapiplus.core.typing import SerializableNotToJson, SerializableOptional
from supersetapiplus.exceptions import LoadJsonError, UnboundModelError

logger = logging.getLogger(__name__)

FieldValue = str | int | bool | None | dict[str, Any] | list[Any]


class ObjectDecoder(json.JSONEncoder):
    """
    Custom JSON encoder that serializes objects containing Enum instances.

    Overrides `json.JSONEncoder.default` so that `Enum` values are converted to
    their string representation (usually `value`), making it easy to serialize
    objects that use Enums as attributes.

    Example:
        >>> class Status(Enum):
        ...     OK = "ok"
        ...     FAIL = "fail"
        >>> json.dumps({'status': Status.OK}, cls=ObjectDecoder)
        '{"status": "ok"}'

    Methods:
        default(obj): returns the value of an Enum instance (a number for integer enums);
                      otherwise delegates to the default behavior.
    """

    def default(self, obj: Any) -> Any:
        # Convert Enum instances to their value: a number for integer enums, a string otherwise
        if isinstance(obj, Enum):
            return enum_value(obj)
        return super().default(obj)


def enum_value(member: Enum) -> Any:
    """Serialized value of an enum member: integer enums (IntEnum) stay numbers, the others are strings."""
    return int(member) if isinstance(member, int) else str(member.value)


class SerializableModel(ParseMixin, ABC):
    """
    Abstract base class for objects that interact with the Superset API.

    Provides:
    - serialization and deserialization via JSON;
    - data validation;
    - conversion to dictionary (`to_dict`) and JSON (`to_json`);
    - support for extra fields not modeled directly;
    - data loading.

    Equality is the one generated by `@dataclass` on each subclass (field by field; `_extra_fields` and other
    technical attributes are not fields); models are mutable and therefore not hashable.

    Every subclass is assumed to be a `dataclass` whose fields mirror the structure expected by the API.

    Attributes:
        _factory: reference to the factory that manages instances of this object.
        JSON_FIELDS (List[str]): fields that must be serialized as JSON strings.
        _extra_fields (Dict): fields not mapped directly to class attributes.
    """
    _factory: Any = None  # repository the object was read or created through (see _repository)
    _request_response: Any = None  # HTTP response the object was read from, if any

    JSON_FIELDS: list[str] = []

    # True on objects built from data stored by Superset (from_json): the checks meant for objects built in
    # code are skipped, so what Superset saved can be written back as read.
    _read_from_superset: bool = False

    # Unmodeled keys read by from_json, per instance (set in __post_init__/from_json). The class default is
    # read-only, so it can never be shared and mutated across instances.
    _extra_fields: Mapping[str, Any] = MappingProxyType({})

    # Re-emit in to_dict the unmodeled fields received in from_json. Needed for Superset's
    # free-form structures (params, query_context, json_metadata), where the library models
    # only some of the keys and dropping the rest would corrupt the object on save.
    # Models of REST endpoints with a strict schema (chart, dashboard, dataset...) disable it.
    PRESERVE_EXTRA_FIELDS = True

    # Fields accepted by the REST endpoint on create (POST) and update (PUT), per the
    # `{Resource}RestApi.post/.put` schemas of Superset's OpenAPI spec (checked in
    # tests/unit/test_openapi_conformance.py). None = no restriction. /_info cannot be used for this:
    # in 6.1.0 ChartRestApi declares add/edit_columns = ['slice_name'].
    POST_FIELDS: tuple[str, ...] | None = None
    PUT_FIELDS: tuple[str, ...] | None = None

    # Relations that GET returns as objects ({"id": 1, "first_name": ...}) and POST/PUT take as ids
    # (owners, roles): kept as read, so the round trip is lossless, and sent as ids by to_json.
    ID_REFERENCE_FIELDS: tuple[str, ...] = ()

    def validate(self) -> None:
        ...

    def __post_init__(self) -> None:
        """
        Run post-initialization steps for Object instances.

        Called automatically after a dataclass instance is created. It has two
        responsibilities:

        1. Deserialize the fields listed in `JSON_FIELDS` that were passed as strings.
           These fields are expected in JSON format and are converted to Python structures.

        2. Assign explicit default values to fields that:
            - have a default value defined;
            - were not filled in (value `None`) at instantiation;
            - are not `SerializableOptional` fields.

        This ensures required fields hold proper values, keeping the object's
        internal state consistent right after creation.
        """


        self._extra_fields = {}
        # Convert JSON_FIELDS passed as strings into Python dictionaries
        for f in self.JSON_FIELDS:
            value = getattr(self, f) or "{}"
            if isinstance(value, str):
                setattr(self, f, json.loads(value))

        # Iterate over all dataclass fields
        for field in self.fields():
            # If the field has a default, is currently None
            # and is not SerializableOptional,
            # set it to its default
            if not isinstance(field.default, dataclasses._MISSING_TYPE) \
                    and getattr(self, field.name) is None \
                    and get_origin(field.type) is not SerializableOptional:
                setattr(self, field.name, field.default)

    @property
    def extra_fields(self) -> dict[str, Any]:
        if not isinstance(self._extra_fields, dict):
            self._extra_fields = {}
        return self._extra_fields

    @classmethod
    def fields(cls) -> set[dataclasses.Field[Any]]:
        """
        Return the set of fields defined in the dataclass.

        Inherited fields included; class-level settings (ClassVar) are not fields.

        Returns:
            set: `dataclasses.Field` objects representing the class fields.
        """
        # dataclasses.fields() leaves out ClassVar and InitVar pseudo-fields (__dataclass_fields__ includes them).
        return set(dataclasses.fields(cast(Any, cls)))

    @classmethod
    def get_field(cls, name: str) -> dataclasses.Field[Any] | None:
        """
        Return the dataclass field with the given name.

        Iterates over all dataclass fields and returns the one whose name
        matches the argument.

        Args:
            name (str): name of the field to look up.

        Returns:
            dataclasses.Field: the matching field, or None if not found.
        """
        for f in cls.fields():
            if f.name == name:
                return f
        return None

    @classmethod
    def field_names(cls) -> list[str]:
        """
        Return the names of all fields defined in the dataclass.

        Fields whose default is an `Object` instance are skipped, since they
        represent complex sub-objects.

        Returns:
            list: names of the relevant fields.
        """
        fields = []
        for f in dataclasses.fields(cast(Any, cls)):  # declaration order (fields() is a set)
            # Skip fields whose default is an Object instance
            if not isinstance(f.default, SerializableModel):
                fields.append(f.name)
        return fields

    @classmethod
    def required_fields(cls, data: dict[str, Any]) -> dict[str, Any]:
        """
        Extract the dataclass's required fields from the given data.

        A field is required when it has no default (`MISSING`) and is not a
        complex `SerializeObject`-based field.

        Args:
            data (dict): raw data to check.

        Returns:
            dict: subset of the data containing only the required fields.
        """
        rdata = {}
        for f in cls.fields():
            if f.default is dataclasses.MISSING and not isinstance(f.default, SerializableModel):
                rdata[f.name] = data.get(f.name)
        return rdata

    @classmethod
    def __get_extra_fields(cls, data: dict[str, Any]) -> dict[str, Any]:
        """
        Extract the extra fields not defined as class attributes.

        Identifies the key-value pairs of `data` that do not match any field defined
        in the class. These "extra" fields are removed from the original dictionary
        and returned separately.

        Args:
            data (dict): input data, usually taken from a JSON response.

        Returns:
            dict: the extra fields not recognized as class attributes.
        """
        # Get the field names defined in the class
        # Get the keys present in the data dictionary
        # Compute the difference to find the unexpected keys
        # Remove and store the fields not defined in the class model

        if not data:
            return {}

        field_names = set(cls.field_names())  # Field names defined in the class

        data_keys = set(data.keys())  # Keys present in the received dictionary
        extra_fields_keys = data_keys - field_names  # Unknown keys
        extra_fields = {}
        for field_name in extra_fields_keys:
            extra_fields[field_name] = data.pop(field_name)  # Remove the extra fields from the original dictionary

        return extra_fields

    @classmethod
    def _subclass_object(cls, field: dataclasses.Field[Any] | None) -> Any:
        """
        Retrieve the `Object` subclass associated with a dataclass field.

        Used to determine dynamically which object type must be instantiated
        while deserializing nested structures.

        The class is looked up at two levels:
        1. the field metadata (`cls`), usually passed through `object_field`;
        2. the `default_factory`, if it is an `Object` subclass.

        Args:
            field (dataclasses.Field): dataclass field whose type is inspected.

        Returns:
            Optional[Type[Object]]: the `Object` subclass, if found; otherwise `None`.
        """

        if field is None:
            return None

        # First try to get the class directly from the metadata, if available
        if hasattr(field, 'metadata'):
            if field.metadata.get("cls"):
                return field.metadata.get("cls")
        else:
            logger.warning(f'Field {field.name} has no "metadata" attribute. '
                           f'\nIf the field type is a subclass of "SerializableModel", '
                           f'check that the field was declared correctly with object_field.')

        # Then try to infer it from the default_factory
        default_factory = getattr(field, 'default_factory', None)

        if default_factory and default_factory is not dataclasses.MISSING:
            if isinstance(default_factory, type) and issubclass(default_factory, SerializableModel):
                return default_factory

        # If neither approach works, return None
        return None

    @classmethod
    def instantiate_with_missing_check(cls, **data: Any) -> Self:
        """
        Instantiate `cls` from keyword arguments, but:

          - Warn if any declared dataclass fields were not provided,
            and inject them into `data` with a `MissingField()` sentinel.
          - Warn if any extra keys were passed in.
          - Finally, call `cls(**filtered_data)` using exactly the declared fields.

        Returns:
            An instance of `cls`.
        """
        # 1) Determine all dataclass field names
        all_fields = {f.name for f in cls.fields()}
        provided = set(data.keys())

        # 2) Find missing and extra
        missing = all_fields - provided
        extra = provided - all_fields

        # 3) Warn and inject sentinel for missing fields
        if missing:
            for name in missing:
                data[name] = MissingField()

        # 4) Warn about any extra keys
        if extra:
            logger.warning(
                "%s: received unknown fields (will be ignored): %s",
                cls.__name__, sorted(extra)
            )
            # (we simply drop them below)

        # 5) Filter to exactly the dataclass fields
        filtered = {k: v for k, v in data.items() if k in all_fields}

        # 6) Instantiate
        return cls(**filtered)

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Self:
        """
        Build an instance of the class from a JSON dictionary.

        Deserializes an object of the class from a dictionary representing its
        attributes. Additional fields not defined in the class are captured in
        `_extra_fields`. It also deserializes nested JSON fields, lists of objects and
        objects with specific metadata, including structures that use `dict_right`.

        During the process, `None` values are replaced by `CUSTOM_NONE` instances,
        preserving the semantics of a missing value without clashing with a literal absence.

        Args:
            data (dict): data to map onto an instance of the class.

        Returns:
            Self: a new instance of the class, populated with the given data.

        Raises:
            LoadJsonError: if mapping any field fails, including structure, type or
                           parsing errors in composite fields.
        """
        extra_fields = cls.__get_extra_fields(data)  # Split off fields not defined in the class
        field_name = None
        try:
            logger.debug('Instantiating %s with data: %s', cls.__name__, mask_data(data))
            obj = cls.instantiate_with_missing_check(**data)
            for field_name in cls.JSON_FIELDS:
                if isinstance(data.get(field_name), str):
                    setattr(obj, field_name, cls._load_json_field(field_name, data[field_name]))
            for field_name, data_value in data.items():
                if field_name not in cls.JSON_FIELDS:
                    setattr(obj, field_name, cls._load_value(field_name, data_value))
            obj._extra_fields = extra_fields
            # Built from data stored by Superset: checks meant for objects built in code are skipped, so
            # what Superset saved can be written back as read (lossless round trip).
            obj._read_from_superset = True
        except Exception as err:
            logger.exception("Error deserializing %s.%s from %s", cls.__name__, field_name, mask_data(data))
            raise LoadJsonError(f"Error deserializing {cls.__name__}.{field_name}: {err}") from err
        return obj

    @classmethod
    def _load_json_field(cls, field_name: str, text: str) -> Any:
        """A field stored as JSON text; 'null' (e.g. the query_context of an imported chart) becomes None."""
        value = json.loads(text)
        serializable_object_class = cls._subclass_object(cls.get_field(field_name))
        if serializable_object_class and value is not None:
            return serializable_object_class.from_json(value)
        return value

    @classmethod
    def _load_value(cls, field_name: str, value: Any) -> Any:
        """A field value with its nested models (a model, a list of models or a `dict_right` dictionary)."""
        if not isinstance(value, (dict, list)):
            return value
        field = cls.get_field(field_name)
        serializable_object_class = cls._subclass_object(field)
        if field is None or not serializable_object_class:
            return value
        if isinstance(value, list):
            return [serializable_object_class.from_json(item) if isinstance(item, dict) else item for item in value]
        if field.metadata.get('dict_right'):
            return {key: serializable_object_class.from_json(item) for key, item in value.items()}
        return serializable_object_class.from_json(value)

    @classmethod
    def _is_exclude(cls, value: FieldValue, field_name: str, convert_to_json: bool = False) -> bool:
        """Whether the field is left out of the dictionary: absent (MissingField), never serialized
        (SerializableNotToJson) or an optional field still unset (SerializableOptional)."""
        if isinstance(value, MissingField):
            return True
        field = cls.get_field(field_name)
        if field is None:  # attribute requested through `columns`, not a model field
            return False
        origin = get_origin(field.type)
        if origin is SerializableNotToJson:
            return True
        return origin is SerializableOptional and _is_unset_optional(field, value)

    def to_dict(self, columns: list[str] | None = None, convert_to_json: bool = False) -> dict[str, Any]:
        """
        Serialize the object into a Python dictionary, converting every relevant field.

        `columns` adds attribute names to the model fields; nested models serialize their own fields.
        Models, enums, lists, (value, key) pairs and dictionaries of models (`dict_left`/`dict_right`
        metadata) are converted recursively. With `convert_to_json`, the fields in `JSON_FIELDS` become
        JSON text and the object is validated.

        Returns:
            dict: dictionary representing the object's current state, with the fields converted.
        """
        data = {}
        # Declaration order, then the extra columns: the query of some plugins follows the key order.
        for field_name in dict.fromkeys([*self.field_names(), *(columns or [])]):
            value = getattr(self, field_name, MissingField())
            if isinstance(value, MissingField):  # absent from the JSON read, or not mapped yet
                continue
            value = self._serialize_value(field_name, value, convert_to_json)
            if self.__class__._is_exclude(value, field_name, convert_to_json):
                continue
            if convert_to_json and field_name in self.JSON_FIELDS:
                # None is sent as null, not as the text "null" (which Superset would store literally).
                value = None if value is None else json.dumps(value, cls=ObjectDecoder)
            data[field_name] = value

        if self.PRESERVE_EXTRA_FIELDS:
            for extra_name, extra_value in (self._extra_fields or {}).items():
                data.setdefault(extra_name, extra_value)
        if data.get('extra_fields'):  # technical attribute, never part of the payload
            data.pop('extra_fields')

        if convert_to_json:
            self.validate()
        return data

    def _serialize_value(self, field_name: str, value: Any, convert_to_json: bool) -> Any:
        """Serialized form of a field value (models, enums, lists, pairs and dictionaries of models)."""
        if isinstance(value, Enum):
            return enum_value(value)
        if not value:
            return value
        if isinstance(value, SerializableModel):
            return value.to_dict(None, convert_to_json)
        if isinstance(value, list):
            return [self._serialize_item(field_name, item, convert_to_json) for item in value]
        if isinstance(value, dict):
            return self._serialize_dict(field_name, value, convert_to_json)
        if isinstance(value, tuple):
            return _serialize_pair(field_name, value, convert_to_json)
        return value

    @staticmethod
    def _serialize_item(field_name: str, item: Any, convert_to_json: bool) -> Any:
        if isinstance(item, SerializableModel):
            return item.to_dict(None, convert_to_json)
        if isinstance(item, tuple):
            return _serialize_pair(field_name, item, convert_to_json)
        if isinstance(item, Enum):
            return enum_value(item)
        return item

    def _serialize_dict(self, field_name: str, value: dict[Any, Any], convert_to_json: bool) -> dict[Any, Any]:
        """Dictionaries whose keys (`dict_left`) or values (`dict_right`) are models, per the field metadata."""
        field = self.get_field(field_name)
        if field is None or not self._subclass_object(field):
            return value
        if field.metadata.get('dict_left'):
            return {obj.to_dict(None, convert_to_json): item for obj, item in value.items()}
        if field.metadata.get('dict_right'):
            return {key: obj.to_dict(None, convert_to_json) for key, obj in value.items()}
        return {}

    def to_json(self, columns: list[str] | None = None) -> dict[str, Any]:
        """
        Serialize the object into a JSON-ready dictionary, with support for nested fields.

        Converts the object into a dictionary suitable for JSON export, applying specific
        serialization rules to the fields in `JSON_FIELDS` (stored as JSON strings),
        dropping unfilled optional fields and excluding fields marked as non-serializable
        (`SerializableNotToJson`).

        Args:
            columns (list, optional): names of the fields to include in the export.
                If omitted, all fields defined in the class are considered.

        Returns:
            dict: dictionary ready for JSON serialization.
        """
        if columns is None:
            columns = []

        # First convert the whole object into a plain dictionary (recursively)
        data = self.to_dict(columns, convert_to_json=True)

        # `columns` restricts the top-level fields (to_dict merges the list with the model fields
        # to serialize nested objects, so without this filter the argument had no effect).
        if columns:
            data = {k: v for k, v in data.items() if k in columns}
        for name in self.ID_REFERENCE_FIELDS:
            if isinstance(data.get(name), list):
                data[name] = [item["id"] if isinstance(item, dict) else item for item in data[name]]

        # Log the final structure before returning it
        logger.debug('return data %s', mask_data(data))

        return data

    # --- persistence: facade over the repository the object was read or created through ---------------

    def _repository(self) -> Any:
        """Repository (``client.charts``, ``client.dashboards``...) the object is bound to."""
        if self._factory is None:
            raise UnboundModelError(
                f"{type(self).__name__} is not bound to a Superset client: create it with client.<resource>.add() "
                "or read it with client.<resource>.get() before calling methods that reach the server.")
        return self._factory

    @property
    def base_url(self) -> str:
        """URL of this object on the REST API."""
        url: str = self._repository().object_url(getattr(self, "id", None))
        return url

    def export(self, path: Path | str) -> None:
        """Export this object to a file (ZIP, JSON or YAML)."""
        self._repository().export(ids=[getattr(self, "id", None)], path=path)

    def fetch(self) -> None:
        """Reload the fields of this object from Superset."""
        self._repository().fetch(self)

    def save(self) -> None:
        """Send the update-accepted fields (PUT_FIELDS) of this object to Superset."""
        self._repository().save(self)

    def delete(self) -> bool:
        """Delete this object from Superset."""
        deleted: bool = self._repository().delete(id=getattr(self, "id", None))
        return deleted


def _field_default(field: dataclasses.Field[Any]) -> Any:
    if field.default is not dataclasses.MISSING:
        return field.default
    if field.default_factory is not dataclasses.MISSING:
        return field.default_factory()
    return None


def _is_unset_optional(field: dataclasses.Field[Any], value: Any) -> bool:
    """An optional field is left out while it holds None (default None) or an empty copy of its model default."""
    default = _field_default(field)
    if value is None:
        return default is None
    return (isinstance(value, dict) and isinstance(default, SerializableModel)
            and dicts_equal_and_all_values_none(value, default.to_dict()))


def _serialize_pair(field_name: str, value: tuple[Any, ...], convert_to_json: bool) -> tuple[Any, ...]:
    """A (value, key) pair, e.g. an orderby item, with each element converted."""
    # A pair is always expected; a tuple of any other length is usually a stray comma in the field
    # declaration of the @dataclass.
    if len(value) != 2:
        raise ValueError(
            f"Invalid default for dataclass field '{field_name}': got tuple of length {len(value)}. "
            "This usually happens when there is an extra comma after a field declaration in a @dataclass "
            "class. Remove the extra comma and try again.")
    return tuple(SerializableModel._serialize_item(field_name, item, convert_to_json) for item in value)
