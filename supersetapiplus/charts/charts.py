# Modeled viz types whose plugin renders through the legacy API (useLegacyApi: true, e.g.
# legacy-plugin-chart-calendar/src/index.ts): their v1 query context, the one Explore saves, does not compute what
# the chart shows (cal_heatmap: superset/viz.py CalHeatmapViz buckets the time; the v1 query returns one row).
LEGACY_API_VIZ_TYPES = frozenset(("cal_heatmap",))


def _unsupported_message(viz_type: str) -> str:
    """Why a viz_type has no model; for a type removed from Superset, what replaced it."""
    if viz_type in REMOVED_VIZ_TYPES:
        return (f"viz_type '{viz_type}' was removed from Superset, which migrated its charts to "
                f"'{REMOVED_VIZ_TYPES[viz_type]}': use that type.")
    if viz_type in REMOVED_WITHOUT_CHART_TYPE:
        return f"viz_type '{viz_type}' was removed from Superset; use the {REMOVED_WITHOUT_CHART_TYPE[viz_type]}."
    return f"viz_type '{viz_type}' is not supported by superset-api-plus."


class Chart(ApiModel):
    """A chart; each modeled viz_type is a subclass that declares VIZ_TYPE and registers itself."""
    # viz_type -> model class, filled by __init_subclass__ (see for_viz_type).
    _REGISTRY: ClassVar[dict[str, type["Chart"]]] = {}
    VIZ_TYPE: ClassVar[ChartType | None] = None

    JSON_FIELDS: ClassVar[list[str]] = ['params', 'query_context']
    PRESERVE_EXTRA_FIELDS: ClassVar[bool] = False
    # Fields accepted by the API (OpenAPI 6.1.0: ChartRestApi.post / ChartRestApi.put).
    POST_FIELDS: ClassVar[tuple[str, ...]] = (
        "cache_timeout", "certification_details", "certified_by", "dashboards", "datasource_id",
        "datasource_name", "datasource_type", "description", "external_url", "is_managed_externally",
        "owners", "params", "query_context", "query_context_generation", "slice_name", "viz_type",
    )
    PUT_FIELDS: ClassVar[tuple[str, ...]] = (
        "cache_timeout", "certification_details", "certified_by", "dashboards", "datasource_id",
        "datasource_type", "description", "external_url", "is_managed_externally", "owners", "params",
        "query_context", "query_context_generation", "slice_name", "tags", "viz_type",
    )
    # Fields that Superset legitimately keeps different between params and
    # query_context.form_data: identity (stale slice_id after dashboard import/export)
    # and request parameters that the frontend injects only into form_data.
    VOLATILE_FORM_DATA_FIELDS: ClassVar[set[str]] = {'slice_id', 'dashboards', 'force', 'result_format', 'result_type'}
    # Suffixes of keys that Superset stores in params but may omit from query_context.form_data
    # (e.g. the query B keys of mixed_timeseries). Only absence is tolerated, not diverging values.
    PARAMS_ONLY_FIELD_SUFFIXES: ClassVar[tuple[str, ...]] = ()

    slice_name: str
    id: int | None = None
    description: str | None = None
    viz_type: ChartType | None = None

    certification_details: str | None = None
    certified_by: str | None = None
    is_managed_externally: bool | None = None
    external_url: SerializableOptional[str] = None
    # Whether the stored query_context was generated by Superset (Explore) rather than sent by a client.
    query_context_generation: SerializableOptional[bool] = None

    # Each chart type declares its own Option class (set from _default_option_class when not given).
    params: Option = None  # type: ignore[assignment]  # set in model_post_init
    # None when Superset stored a null query_context (charts never saved from Explore): edits then go to
    # params only, and derive_query_context() rebuilds it on save.
    query_context: QueryContext | None = Field(default_factory=QueryContext)

    datasource_id: SerializableOptional[int] = None
    datasource_type: SerializableOptional[DatasourceType] = DatasourceType.TABLE
    cache_timeout: int | None = None

    dashboards: SerializableNotToJson[list[Dashboard]] = Field(default_factory=list)
    owners: SerializableNotToJson[list[dict[str, Any]] | None] = None

    tags: SerializableNotToJson[list[Any] | None] = None

    changed_on_delta_humanized: SerializableNotToJson[str | None] = None
    thumbnail_url: SerializableNotToJson[str | None] = None
    url: SerializableNotToJson[str | None] = None

    _slice_name_override: str | None = None
    _dashboards: list[Any] = PrivateAttr(default_factory=list)
    # Rebuild the query_context from params on save (charts built in code; see derive_query_context).
    _derive_query_context: bool = False
    # Keep builder ordering when the caller overrides the UI's default ordering.
    _preserve_query_orderby: bool = False
    # Temporal columns of the dataset, set by the repository before a save (see explore_form_data).
    _dataset_time: DatasetTime | None = None


    @classmethod
    @abstractmethod
    def _default_option_class(cls) -> type[Option]:
        ...

    def model_post_init(self, context: Any) -> None:
        super().model_post_init(context)
        self._dashboards = [Dashboard(dashboard_title='')]

        if not hasattr(self, "params") or self.params is None:
            self.params = self._default_option_class()()  # Assumes the concrete subclass defines this method

        # Charts built in code send the query_context the Superset UI would derive from params
        # (build_query); charts read from Superset keep the stored one (lossless round trip).
        self._derive_query_context = self.id is None

        if self.id is None:
            if self.datasource_id is None:
                raise ChartValidationError("""
                    When id is None, argument datasource id becomes mandatory.
                    We recommend using the [client_superset].datasets.get_id_by_name('name_dataset') method
                    to get the dataset id by name.
                """)

            self._fill_datasource()

    def _fill_datasource(self) -> None:
        """New chart: params (and query_context) get the datasource from datasource_id/datasource_type.

        Called in __post_init__ and again at the end of from_json: during from_json, __post_init__
        runs while params is still a dict (the conversion to Option happens later).
        """
        if self.id is not None or self.datasource_id is None or not isinstance(self.params, ApiModel):
            return
        if not self.params.datasource:  # None or MissingField (absent from the JSON)
            self.params.datasource = f'{self.datasource_id}__{self.datasource_type}'
            if isinstance(self.query_context, ApiModel):
                self.query_context.datasource.id = self.datasource_id
                self.query_context.form_data = copy.deepcopy(self.params)

    def _repair_query_context_datasource(self) -> None:
        """Chart read from Superset: a null query_context datasource id or type gets datasource_id/datasource_type.

        Superset cannot process the null (int(None) in common/query_context_factory.py, so GET
        /dashboard/{id}/datasets answers 422): the one exception to writing back what was read. A non-null id that
        differs from datasource_id is kept as read.
        """
        datasource = self.query_context.datasource if self.query_context is not None else None
        if self.id is None or self.datasource_id is None or not isinstance(datasource, DataSource):
            return
        if datasource.id is not None and datasource.type is not None:
            return
        warnings.warn(NullQueryContextDatasourceWarning(
            f"chart {self.id}: query_context datasource {{'id': {datasource.id}, 'type': {datasource.type}}} filled "
            f"from the chart datasource {self.datasource_id}__{self.datasource_type}"), stacklevel=3)
        if datasource.id is None:
            datasource.id = self.datasource_id
        if datasource.type is None:
            datasource.type = self.datasource_type

    def validate(self) -> None:  # type: ignore[override]  # facade method, not pydantic's deprecated classmethod
        super().validate()
        # A null query_context (chart never saved from Explore) or one without form_data (example charts
        # loaded from YAML in Superset 6.1) has nothing to compare with params.
        if self.query_context is None or not isinstance(self.query_context.form_data, ApiModel):
            return

        # Plugins may augment the derived form_data (raw tables add include_time=False).
        expected = self.ui_query_context()['form_data'] if self._derive_query_context else self.params.to_dict()
        params = {k: v for k, v in expected.items() if k not in self.VOLATILE_FORM_DATA_FIELDS}
        form_data = {k: v for k, v in self.query_context.form_data.to_dict().items()
                     if k not in self.VOLATILE_FORM_DATA_FIELDS}
        # Old Superset versions stored form_data.datasource as "None__table";
        # params remains the source of truth and Superset ignores the invalid value.
        if str(form_data.get('datasource', '')).startswith('None__'):
            form_data['datasource'] = params.get('datasource')
        if self.PARAMS_ONLY_FIELD_SUFFIXES:
            params = {k: v for k, v in params.items()
                      if k in form_data or not k.endswith(self.PARAMS_ONLY_FIELD_SUFFIXES)}
        if getattr(self, '_read_from_superset', False):
            # Older Superset versions stored a form_data without some params keys (e.g. annotation_layers):
            # for a chart read from Superset only absence is tolerated, not diverging values.
            params = {k: v for k, v in params.items() if k in form_data}
        if params != form_data:
            added, removed, modified, same = detailed_dict_diff(params, form_data)

            raise ValidationError(message=f'self.params is not the same as self.query_context.form_data. '
                                          f'Diff: modified={modified}, added={added}, removed={removed}',
                                  solution="We recommend using the public methods of the chart class.")

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        if cls.__dict__.get('VIZ_TYPE') is not None:
            Chart._REGISTRY[str(cls.VIZ_TYPE)] = cls

    @classmethod
    def for_viz_type(cls, viz_type: str) -> type["Chart"]:
        """Model class of a viz_type, importing its module (supersetapiplus.charts.<viz_type>) on demand.

        Raises:
            UnsupportedTypeError: the library has no model for the viz_type.
        """
        viz_type = str(viz_type)
        if viz_type not in Chart._REGISTRY:
            module_name = f"{__package__}.{viz_type}"
            try:
                importlib.import_module(module_name)
            except ModuleNotFoundError as error:
                if error.name != module_name:
                    raise
        try:
            return Chart._REGISTRY[viz_type]
        except KeyError:
            raise UnsupportedTypeError(_unsupported_message(viz_type)) from None

    @classmethod
    def get_class(cls, type_: str, module_name: str | None = None) -> type["Chart"]:
        """Model class of a viz_type (kept for compatibility; `module_name` is no longer needed)."""
        return cls.for_viz_type(type_)

    @classmethod
    def instance(cls,
                 slice_name: str,
                 datasource: DataSource,
                 options: Option | None = None) -> Self:

        if options is None:
            options = cls._default_option_class()()  # delegates to the subclass

        new_chart = cls(slice_name=slice_name,
                        datasource_id=datasource.id,
                        datasource_type=datasource.type)

        options.datasource = f'{datasource.id}__{datasource.type}'

        new_chart.params = options
        if new_chart.query_context is not None:
            new_chart.query_context.form_data = copy.deepcopy(options)
        return new_chart

    def add_dashboard(self, dashboard: Dashboard) -> None:
        self.dashboards.append(dashboard)
        if self.query_context is not None and dashboard.id is not None:
            self.query_context.add_dashboard(dashboard.id)

    def clone(self, slice_name: str | None = None, slice_name_override: str | None = None, clear_dashboard: bool = False,
              clear_filter: bool = True) -> Self:
        new_chart = copy.deepcopy(self)
        new_chart.slice_name = slice_name or f'{new_chart.slice_name}_clone'
        new_chart._slice_name_override = slice_name_override or f'Chart clone of {new_chart.slice_name}'
        new_chart.id = 0

        if clear_dashboard:
            new_chart.dashboards = []
        if clear_filter:
            new_chart.clear_filter()

        return new_chart

    def clear_filter(self) -> None:
        self.params.adhoc_filters = []
        if self.query_context is not None:
            for query in self.query_context.queries:
                query.filters = []
            self.query_context.form_data.adhoc_filters = []

    def add_simple_metric(self, metric: MetricType, automatic_order: OrderBy = OrderBy()) -> None:
        self.params._add_simple_metric(metric, automatic_order)
        if self.query_context is not None:
            self.query_context._add_simple_metric(metric, automatic_order)
            self._preserve_query_orderby |= automatic_order != OrderBy()

    def add_custom_metric(self, label: str,
                          automatic_order: OrderBy = OrderBy(),
                          column: AdhocMetricColumn | None = None,
                          sql_expression: str | None = None,
                          aggregate: MetricType | None = None) -> None:
        self.params._add_custom_metric(label, automatic_order, column, sql_expression, aggregate)
        if self.query_context is not None:
            self.query_context._add_custom_metric(label, automatic_order, column, sql_expression, aggregate)
            self._preserve_query_orderby |= automatic_order != OrderBy()

    def add_simple_orderby(self, column_name: str,
                            sort_ascending: bool = True) -> None:
        if self.query_context is not None:
            self.query_context._add_simple_orderby(column_name, sort_ascending)
            self._preserve_query_orderby = True

    def add_custom_orderby(self, label: str,
                             sort_ascending: bool,
                             column: AdhocMetricColumn | None = None,
                             sql_expression: str | None = None,
                             aggregate: MetricType | None = None) -> None:
        if self.query_context is not None:
            self.query_context._add_custom_orderby(label, sort_ascending, column, sql_expression, aggregate)
            self._preserve_query_orderby = True

    def add_simple_dimension(self, column_name: str) -> None:
        self.params._add_simple_groupby(column_name)
        if self.query_context is not None:
            self.query_context._add_simple_groupby(column_name)

    def add_custom_dimension(self, label: str,
                             column: AdhocMetricColumn | None = None,
                             sql_expression: str | None = None,
                             aggregate: MetricType | None = None) -> None:
        self.params._add_custom_groupby(label, column, sql_expression, aggregate)
        if self.query_context is not None:
            self.query_context._add_custom_groupby(label, column, sql_expression, aggregate)

    def add_simple_filter(self, column_name: str,
                          value: FilterValues | None = None,
                          operator: FilterOperatorType = FilterOperatorType.EQUALS) -> None:
        """Filter on a column: one value, a list for IN/NOT IN, none for IS NULL and the other IS operators."""
        value = filter_comparator(operator, value)
        self.params._adhoc_filters(expression_type=FilterExpressionType.SIMPLE,
                                   clause=FilterClausesType.WHERE,
                                   subject=column_name,
                                   comparator=value,
                                   operator=operator)
        if self.query_context is not None:
            self.query_context._add_simple_filter(column_name=column_name, value=value, operator=operator)

    def add_extra_where(self, sql: str) -> None:
        self.params._adhoc_filters(expression_type=FilterExpressionType.CUSTOM_SQL,
                                   clause=FilterClausesType.WHERE,
                                   sql_expression=sql)
        if self.query_context is not None:
            self.query_context._add_extra_where(sql)

    def add_extra_having(self, sql: str) -> None:
        if self.query_context is not None:
            self.query_context._add_extra_having(sql)

    def use_dataset_time(self, dataset: DatasetTime) -> None:
        """The temporal columns of the chart's dataset, which Explore reads besides the params (default time filter,
        temporal dimensions, time grain shown). ``client.charts.add`` and ``save`` set them before sending.

        A chart built in code also gets, as a new chart in the UI, a TEMPORAL_RANGE filter when it has none
        (datePickerInAdhocFilterMixin, mixins.tsx): the filter a time range native filter of a dashboard applies to.
        It is the legacy time column and range of the params when both are set, else "No filter" on the dataset's
        default temporal column.
        """
        self._dataset_time = dataset
        if self.id is not None or self._read_from_superset:
            return
        controls = QUERY_CONTROLS.get(str(self.viz_type), frozenset())
        filters = self.params.adhoc_filters if isinstance(self.params.adhoc_filters, list) else []
        if "adhoc_filters" not in controls or "time_range" in controls \
                or any(_operator(item) == FilterOperatorType.TEMPORAL_RANGE for item in filters):
            return
        subject, comparator = self._legacy_time_range() or (dataset.default, NO_TIME_RANGE)
        if subject:
            self.params.adhoc_filters = [*filters, AdhocFilterClause(
                subject=subject, operator=FilterOperatorType.TEMPORAL_RANGE, comparator=comparator)]

    def _legacy_time_range(self) -> tuple[str, str] | None:
        """The legacy time column and range of the params (``since``/``until`` read as ``time_range``)."""
        values = {key: self.params.extra_fields.get(key, getattr(self.params, key, None))
                  for key in ("granularity_sqla", "time_range", "since", "until")}
        legacy = {key: value for key, value in values.items() if value is not None}
        update_time_range(legacy)
        column, time_range = legacy.get("granularity_sqla"), legacy.get("time_range")
        if isinstance(column, str) and column and isinstance(time_range, str) and time_range:
            return column, time_range
        return None

    def derive_query_context(self, enabled: bool = True) -> None:
        """Rebuild the query_context from params on the next save, as Explore does when the chart is saved.

        Enabled automatically for charts built in code; call it on a chart read from Superset after
        changing its params, so the stored query_context (used by /chart/{id}/data, reports and cache
        warm-up) follows them.
        """
        self._derive_query_context = enabled

    def ui_query_context(self) -> dict[str, Any]:
        """Query context the Superset UI derives from the current params (frontend buildQuery, 6.1.0).

        The queries are built from the form_data Explore makes of the params (:func:`explore_form_data`: legacy
        params migrated, control defaults, keys that are not controls left out); the ``form_data`` of the context
        stays the params, so what Superset stored reads back the same. The dataset is the chart's
        (`datasource_id`/`datasource_type`), as in the form_data Superset gives Explore (``Slice.form_data``,
        models/slice.py): `params.datasource` may be stale, e.g. in charts imported from another instance.
        """
        form_data = self.params.to_dict()
        if isinstance(self.datasource_id, int) and self.datasource_type:
            form_data["datasource"] = f"{self.datasource_id}__{self.datasource_type}"
        explored = explore_form_data(form_data, self._control_defaults(), self._dataset_time)
        context = query_context_for(explored)
        # Keys a plugin adds to the form_data for its query (raw tables: include_time) are kept.
        context["form_data"] = {**form_data, **{key: value for key, value in context["form_data"].items()
                                                if key not in explored}}
        return context

    @classmethod
    def _control_defaults(cls) -> dict[str, Any]:
        """The params of a new chart of this type: the control defaults of the UI (test_ui_defaults.py)."""
        defaults: dict[str, Any] = cls._default_option_class()().to_dict()
        return defaults

    def _derived_query_context(self) -> QueryContext:
        template = type(self).model_fields['query_context'].get_default(call_default_factory=True)
        # Load the UI payload losslessly: plugin queries may omit metrics or orderby.
        context: QueryContext = type(template).from_json(self.ui_query_context())
        if self._preserve_query_orderby and self.query_context is not None and self.query_context.queries:
            # The builder methods target one query. Keep auxiliary queries (totals, row count, etc.)
            # as the plugin derived them, and do not copy stale filters, columns or metrics.
            context.queries[0].orderby = copy.deepcopy(self.query_context.queries[0].orderby)
        return context

    def to_json(self, columns: list[str] | None = None) -> dict[str, Any]:
        chart = self
        if getattr(self, '_derive_query_context', False) and (not columns or 'query_context' in columns) \
                and isinstance(self.params, ApiModel):
            self.params._check_tree()
            context = self._derived_query_context()
            # Validate and serialize the replacement, keeping the stored context on the original chart.
            chart = self.model_copy(update={'query_context': context})
        return super(Chart, chart).to_json(columns)

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Self:
        obj = super().from_json(data)
        obj._dashboards = obj.dashboards

        # Superset keeps query_context null on charts that were never saved from Explore
        # (common in imported charts). Preserve the null instead of fabricating an empty context.
        if data.get('query_context') in (None, '', 'null'):
            obj.query_context = None

        # Datasource: GET /chart/{id} returns datasource_id/datasource_type at the top level, which prevail;
        # params.datasource may be stale (e.g. imported example charts).
        if data.get('datasource_id'):
            obj.datasource_id = int(data['datasource_id'])
            obj.datasource_type = DatasourceType(data.get('datasource_type') or 'table')
        elif obj.query_context:
            datasource = obj.query_context.datasource
            if datasource and datasource.id:
                obj.datasource_id = datasource.id
                obj.datasource_type = datasource.type
            else:
                logger.warning("datasource query_context without 'id' defined")
        elif isinstance(obj.params, ApiModel) and '__' in str(obj.params.datasource or ''):
            # Listings with restricted columns (find(columns=[...])) do not include params: the partial
            # object has no datasource and is completed by find_one(..., full=True).
            datasource_id, datasource_type = str(obj.params.datasource).split('__', 1)
            obj.datasource_id = int(datasource_id)
            obj.datasource_type = DatasourceType(datasource_type)

        obj._fill_datasource()
        obj._repair_query_context_datasource()
        obj._derive_query_context = obj.id is None
        return obj


def _operator(adhoc_filter: object) -> object:
    if isinstance(adhoc_filter, dict):
        return adhoc_filter.get("operator")
    return getattr(adhoc_filter, "operator", None)


class Charts(ApiModelFactories):
    endpoint = "chart/"
    TYPE_COLUMN = "viz_type"

    def _default_object_class(self) -> type[ApiModel]:
        return Chart

    def add(self, obj: ApiModel) -> int:
        """Creates the chart; one built in code first gets the dataset's temporal columns (see
        :meth:`Chart.use_dataset_time`)."""
        self._read_dataset_time(obj)
        return super().add(obj)

    def save(self, obj: ApiModel) -> None:
        self._read_dataset_time(obj)
        super().save(obj)

    def _read_dataset_time(self, obj: ApiModel) -> None:
        """The temporal columns of the dataset of a chart whose query_context is derived on send."""
        if not isinstance(obj, Chart) or not obj._derive_query_context or obj.datasource_type != DatasourceType.TABLE \
                or not isinstance(obj.datasource_id, int):
            return
        url = self.client.join_urls(self.client.base_url, Datasets.endpoint, obj.datasource_id)
        dataset = self.client.get(url).json()["result"]
        obj.use_dataset_time(DatasetTime(
            columns=tuple(c["column_name"] for c in dataset.get("columns") or [] if c.get("is_dttm")),
            main=dataset.get("main_dttm_col")))

    def get_chart_data(self, slice_id: int, dashboard_id: int | None = None) -> list[dict[str, Any]]:
        """
        Chart data computed by Superset from the saved query_context (GET /chart/{pk}/data/).

        For a legacy viz_type (:data:`LEGACY_API_VIZ_TYPES`, e.g. cal_heatmap) the result is not what the chart
        shows: the chart renders through /superset/explore_json, and its v1 query context gives one aggregate row
        (a LegacyChartDataWarning is emitted). Reports and alerts on the v1 endpoint have the same limitation.

        Args:
            slice_id: chart id.
            dashboard_id: if given, checks that the chart belongs to this dashboard.

        Returns:
            list[dict]: one item per query of the query_context (`data`, `colnames`, `rowcount`...).
        """
        chart = self.client.get(self.client.join_urls(self.base_url, slice_id)).json()["result"]
        if dashboard_id is not None and dashboard_id not in [int(d["id"]) for d in chart.get("dashboards") or []]:
            raise NotFound(f'Chart {slice_id} does not belong to dashboard {dashboard_id}.')
        if chart.get("viz_type") in LEGACY_API_VIZ_TYPES:
            warnings.warn(LegacyChartDataWarning(
                f"Chart {slice_id} is a {chart['viz_type']} (legacy API): its /chart/{{id}}/data result is not what "
                "the chart shows."), stacklevel=2)
        url = self.client.join_urls(self.base_url, slice_id, "data/")
        results: list[dict[str, Any]] = self.client.get(url, params={"format": "json", "type": "full"}).json()["result"]
        return results

    def dashboard_ids(self, chart_id: int) -> list[int]:
        """Ids of the dashboards associated with the chart, as stored by Superset."""
        result = self.client.get(self.client.join_urls(self.base_url, chart_id)).json()["result"]
        return [int(d["id"]) for d in result.get("dashboards") or []]

    def add_to_dashboard(self, chart: Chart | int, dashboard_id: int) -> list[int]:
        """Associates the chart with the dashboard, keeping existing associations (see DashboardCharts)."""
        updated: list[int] = self.client.dashboard_charts.add_to_dashboard(chart, dashboard_id)
        return updated

    def add_and_attach_to_dashboard(self, chart: Chart, title: str, parent: LayoutParent = None) -> int:
        """Creates the chart and places it in the dashboard of the source chart (see DashboardCharts)."""
        new_id: int = self.client.dashboard_charts.add_and_attach_to_dashboard(chart, title, parent)
        return new_id
