def str_fields() -> dict[str, str]:
    """`str` fields of the package dataclasses, keyed by the class that declares each field."""
    found = {}
    for info in pkgutil.walk_packages(supersetapiplus.__path__, "supersetapiplus."):
        if info.name.endswith("graphviz"):  # optional dependency (graphviz)
            continue
        for obj in vars(_import_quietly(info.name)).values():
            if not (isinstance(obj, type) and dataclasses.is_dataclass(obj)
                    and obj.__module__.startswith("supersetapiplus.")):
                continue
            names = {f.name for f in dataclasses.fields(obj)}
            for cls in obj.__mro__:
                for name, annotation in inspect.get_annotations(cls).items():
                    text = annotation if isinstance(annotation, str) else repr(annotation)
                    text = re.sub(r"dict\[str,", "dict[<key>,", text)  # dictionary keys are not str attributes
                    if name in names and re.search(r"\bstr\b", text):
                        module = cls.__module__.removeprefix("supersetapiplus.")
                        found[f"{module}.{cls.__qualname__}.{name}"] = text
    return found


def test_every_str_field_is_declared():
    undeclared = sorted(set(str_fields()) - set(FREE_TEXT))

    assert undeclared == [], ("str fields not checked against the Superset source: type them with an enum or "
                              f"declare them in FREE_TEXT with the reason: {undeclared}")


def test_declared_free_text_fields_still_exist_as_str():
    stale = sorted(set(FREE_TEXT) - set(str_fields()))

    assert stale == [], f"FREE_TEXT entries that are no longer str fields (remove them): {stale}"


def test_every_free_text_field_has_a_reason():
    assert all(reason.strip() for reason in FREE_TEXT.values())


def _import_quietly(name: str):
    """Modules of the package, including the compatibility modules of old paths (they warn on import)."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", DeprecationWarning)
        return importlib.import_module(name)
