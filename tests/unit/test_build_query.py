def test_chart_built_in_code_sends_the_ui_query_context():
    chart = TableChart(slice_name="T", datasource_id=7, datasource_type="table")
    chart.add_simple_metric("count")
    chart.add_simple_dimension("campus")

    sent = json.loads(chart.to_json()["query_context"])

    assert sent == chart.ui_query_context()
    assert sent["queries"][0]["columns"] == ["campus"] and sent["queries"][0]["metrics"] == ["count"]


def test_chart_read_from_superset_keeps_its_query_context_until_asked():
    params = {"datasource": "7__table", "viz_type": "table", "query_mode": "aggregate", "groupby": ["a"],
              "metrics": ["count"]}
    stored = {"datasource": {"id": 7, "type": "table"}, "queries": [{"columns": ["kept"], "metrics": ["count"]}],
              "form_data": params}
    data = {"id": 3, "slice_name": "T", "viz_type": "table", "datasource_id": 7, "datasource_type": "table",
            "params": json.dumps(params), "query_context": json.dumps(stored)}
    chart = Chart.get_class("table", "supersetapiplus.charts.table").from_json(data)

    assert json.loads(chart.to_json()["query_context"])["queries"] == stored["queries"]

    chart.derive_query_context()

    assert json.loads(chart.to_json()["query_context"])["queries"][0]["columns"] == ["a"]


def test_pivot_dimension_added_in_code_is_a_row_and_reaches_the_query():
    from supersetapiplus.charts.pivot_table_v2 import PivotTableV2Chart

    chart = PivotTableV2Chart(slice_name="P", datasource_id=7, datasource_type="table")
    chart.add_simple_metric("count")
    chart.add_simple_dimension("campus")

    params = json.loads(chart.to_json()["params"])
    assert params["groupbyRows"] == ["campus"] and "groupby" not in params
    assert json.loads(chart.to_json()["query_context"])["queries"][0]["columns"] == ["campus"]
