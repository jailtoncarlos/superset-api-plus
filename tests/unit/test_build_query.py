"""Port of the frontend buildQuery vs. the query_context the Superset 6.1.0 frontend sends.

The references (tests/fixtures/ui_query_contexts_6.1.0) are generated by bin/scripts/extract_query_contexts.py:
the body of POST /api/v1/chart/data when each example chart is opened in Explore, i.e. the form_data given to
buildQuery and the queries it produced. The other tests cover operators the examples do not use; their
expected values follow the TypeScript sources cited in supersetapiplus/charts/build_query.py.
"""
import json
from pathlib import Path

import pytest

from supersetapiplus.charts import build_query as bq
from supersetapiplus.charts.charts import Chart
from supersetapiplus.charts.table import TableChart

FIXTURES = Path(__file__).parent.parent / "fixtures"
CAPTURES = FIXTURES / "ui_query_contexts_6.1.0"
VIZ_TYPES = sorted(p.stem for p in CAPTURES.glob("*.json") if p.stem != "INDEX")
BASE = {"datasource": "7__table", "viz_type": "table", "adhoc_filters": [], "extra_form_data": {}}


def form_data_of(viz_type: str) -> dict:
    """The form_data given to buildQuery. For mixed_timeseries the request carries the form data of query A
    only (removeFormDataSuffix), so the "_b" controls come from the saved chart params."""
    form_data = dict(json.loads((CAPTURES / f"{viz_type}.json").read_text())["form_data"])
    saved = FIXTURES / "ui_references_6.1.0" / f"{viz_type}.json"
    if saved.exists():  # legacy charts captured on save (cal_heatmap) have no example reference
        params = json.loads(json.loads(saved.read_text())["params"])
        form_data.update({k: v for k, v in params.items() if k.endswith("_b")})
    return form_data


def queries(context: dict) -> list:
    # url_params carries the Explore slice_id; the references drop it as instance-dependent.
    return [{k: v for k, v in q.items() if k != "url_params"} for q in context["queries"]]


@pytest.mark.parametrize("viz_type", VIZ_TYPES)
def test_query_context_is_the_one_built_by_the_frontend(viz_type):
    reference = json.loads((CAPTURES / f"{viz_type}.json").read_text())

    context = bq.query_context_for(form_data_of(viz_type))

    assert queries(context) == reference["queries"]
    assert (context["result_format"], context["result_type"]) == (reference["result_format"],
                                                                  reference["result_type"])


def test_datasource_key_and_form_data_are_kept():
    context = bq.query_context_for({**BASE, "metrics": ["count"]})

    assert context["datasource"] == {"id": 7, "type": "table"}
    assert context["form_data"]["datasource"] == "7__table" and context["force"] is False


def test_filters_split_into_simple_where_and_freeform_clauses():
    form_data = {**BASE, "adhoc_filters": [
        {"clause": "WHERE", "expressionType": "SIMPLE", "subject": "a", "operator": "IS NOT NULL"},
        {"clause": "WHERE", "expressionType": "SQL", "sqlExpression": "b > 1 -- note"},
        {"clause": "HAVING", "expressionType": "SQL", "sqlExpression": "count(*) > 2"},
    ], "extra_form_data": {"filters": [{"col": "c", "op": "IN", "val": ["x"]}]}}

    (query,) = bq.build_default(form_data)["queries"]

    # processFilters starts from the extra filters and then appends the simple adhoc filters.
    assert query["filters"] == [{"col": "c", "op": "IN", "val": ["x"]}, {"col": "a", "op": "IS NOT NULL"}]
    assert query["extras"]["where"] == "(b > 1 -- note\n)" and query["extras"]["having"] == "(count(*) > 2)"


def test_raw_mode_table_sends_no_metrics_and_columns_in_order():
    (query,) = bq.build_table({**BASE, "query_mode": "raw", "all_columns": ["a", "b"], "metrics": ["count"]})[
        "queries"]

    assert "metrics" not in query and query["columns"] == ["a", "b"]


def test_aggregate_table_orders_by_first_metric_adds_percent_metrics_and_totals():
    form_data = {**BASE, "query_mode": "aggregate", "groupby": ["a"], "metrics": ["count"],
                 "percent_metrics": ["sum__x"], "show_totals": True, "row_limit": 10}

    main, totals = bq.build_table(form_data)["queries"]

    assert main["orderby"] == [["count", False]] and main["metrics"] == ["count", "sum__x"]
    assert main["post_processing"] == [{"operation": "contribution", "options": {
        "columns": ["sum__x"], "rename_columns": ["%sum__x"]}}]
    assert totals["columns"] == [] and totals["row_limit"] == 0 and "orderby" not in totals


def test_server_paginated_table_adds_the_row_count_query():
    form_data = {**BASE, "all_columns": ["a"], "server_pagination": True, "server_page_length": 20,
                 "row_limit": 1000}

    page, rowcount = bq.build_table(form_data)["queries"]

    assert (page["row_limit"], page["row_offset"]) == (20, 0)
    assert rowcount["is_rowcount"] is True and rowcount["row_limit"] == 1000


def test_timeseries_time_comparison_operators():
    form_data = {**BASE, "viz_type": "echarts_timeseries_line", "x_axis": "ds", "metrics": ["count"],
                 "groupby": [], "comparison_type": "difference", "time_compare": ["1 year ago"],
                 "rolling_type": "cumsum", "resample_method": "zerofill", "resample_rule": "1D"}

    (query,) = bq.query_context_for(form_data)["queries"]

    operations = [rule["operation"] for rule in query["post_processing"]]
    assert operations == ["pivot", "resample", "cum", "compare", "rename", "flatten"]
    assert query["post_processing"][4]["options"]["columns"] == {"difference__count__count__1 year ago": "1 year ago"}
    assert query["time_offsets"] == ["1 year ago"]
    assert query["post_processing"][1]["options"] == {"method": "asfreq", "rule": "1D", "fill_value": 0}
    assert query["post_processing"][3]["options"]["compare_columns"] == ["count__1 year ago"]
    assert query["columns"][0]["columnType"] == "BASE_AXIS"


def test_bar_sorted_by_x_axis_uses_the_sort_operator():
    form_data = {**BASE, "viz_type": "echarts_timeseries_bar", "x_axis": "ds", "metrics": ["count"],
                 "x_axis_sort": "ds", "x_axis_sort_asc": False}

    (query,) = bq.query_context_for(form_data)["queries"]

    assert {"operation": "sort", "options": {"is_sort_index": True, "ascending": False}} in query["post_processing"]


@pytest.mark.parametrize("interval, periods, expected", [
    ("0.8", "10", (10, 0.8)),
    ("0.9 ", " 7 days", (7, 0.9)),
    (None, None, (None, None)),
    ("abc", "x", (None, None)),
])
def test_forecast_options_follow_parse_int_and_parse_float(interval, periods, expected):
    """prophetOperator: parseInt/parseFloat give NaN for missing values and JSON.stringify writes it as null."""
    form_data = {**BASE, "viz_type": "echarts_timeseries_line", "x_axis": "ds", "metrics": ["count"],
                 "forecastEnabled": True, "forecastInterval": interval, "forecastPeriods": periods}

    context = bq.query_context_for(form_data)

    (prophet,) = [rule for rule in context["queries"][0]["post_processing"] if rule["operation"] == "prophet"]
    assert (prophet["options"]["periods"], prophet["options"]["confidence_interval"]) == expected
    json.dumps(context, allow_nan=False)


