"""The extraction scripts fail when a symbol disappears or changes shape, instead of producing an empty set.

The conformance tests compare the library with excerpts generated by bin/scripts; an extractor that returned
an empty set for a renamed symbol would make them compare against nothing. These tests run the extraction
functions on synthetic sources, without network.
"""
import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parents[2] / "bin" / "scripts" / "extract_superset_enums.py"
spec = importlib.util.spec_from_file_location("extract_superset_enums", SCRIPT)
extract = importlib.util.module_from_spec(spec)
spec.loader.exec_module(extract)

CONSTANTS_TS = """
export enum Operators {
  Equals = 'EQUALS',
  In = 'IN',
}
export const GRID_COLUMN_COUNT = 12;
export const SMART_DATE_ID = 'smart_date';
export const MULTI_OPERATORS = new Set([Operators.In]);
export const AGGREGATES = {
  SUM: 'SUM',
};
export enum LabelType {
  Key,
  Value,
  Total = 5,
  Rest,
}
export const aggregationChoices = {
  raw: {
    label: 'Overall value',
  },
  LAST_VALUE: {
    label: 'Last Value',
  },
} as const;
const sortAxisChoices = [
  ['alpha_asc', t('Axis ascending')],
  ['value_desc', t('Metric descending')],
];
"""
CONTROL_PANEL_TS = """
        {
          name: 'legendType',
          config: {
            choices: [
              ['scroll', t('Scroll')],
              ['plain', t('Plain')],
            ],
          },
        },
"""
PYTHON = '''
class ErrorLevel(StrEnum):
    INFO = "info"

class MigrateBar(MigrateViz):
    source_viz_type = "bar"
    target_viz_type = "echarts_timeseries_bar"
'''


@pytest.mark.parametrize("function, args, expected", [
    (extract.typescript_enum, ("Operators",), {"Equals": "EQUALS", "In": "IN"}),
    (extract.typescript_numbers, ("^GRID_",), {"GRID_COLUMN_COUNT": 12}),
    (extract.typescript_constants, ("^SMART_DATE_ID$",), {"SMART_DATE_ID": "smart_date"}),
    (extract.typescript_object, ("AGGREGATES",), {"SUM": "SUM"}),
    (extract.operator_group, ("MULTI_OPERATORS",), ["In"]),
    (extract.numeric_enum, ("LabelType",), {"Key": 0, "Value": 1, "Total": 5, "Rest": 6}),
    (extract.object_keys, ("aggregationChoices",), ["raw", "LAST_VALUE"]),
    (extract.array_choices, ("sortAxisChoices",), ["alpha_asc", "value_desc"]),
])
def test_typescript_symbols_are_extracted(function, args, expected):
    assert function(CONSTANTS_TS, *args) == expected


def test_choices_and_python_symbols_are_extracted():
    assert extract.control_choices(CONTROL_PANEL_TS, "legendType") == ["scroll", "plain"]
    assert extract.python_enum(PYTHON, "ErrorLevel") == {"INFO": "info"}
    assert extract.migrated_viz_types(PYTHON) == {"bar": "echarts_timeseries_bar"}


@pytest.mark.parametrize("function, args", [
    (extract.typescript_enum, ("Operators",)),
    (extract.typescript_numbers, ("^GRID_",)),
    (extract.typescript_constants, ("^SMART_DATE_ID$",)),
    (extract.typescript_object, ("AGGREGATES",)),
    (extract.operator_group, ("MULTI_OPERATORS",)),
    (extract.numeric_enum, ("LabelType",)),
    (extract.object_keys, ("aggregationChoices",)),
    (extract.array_choices, ("sortAxisChoices",)),
])
def test_a_removed_typescript_symbol_fails_the_extraction(function, args):
    with pytest.raises((ValueError, SystemExit)):
        function("export const SOMETHING_ELSE = 1;\n", *args)


def test_a_symbol_whose_format_changed_fails_instead_of_giving_an_empty_set():
    double_quotes = CONSTANTS_TS.replace("'", '"')
    with pytest.raises(ValueError, match="nothing found for 'Operators'"):
        extract.typescript_enum(double_quotes, "Operators")
    with pytest.raises(ValueError, match="legendType"):
        extract.control_choices(CONTROL_PANEL_TS.replace("['", '["').replace("',", '",'), "legendType")
    with pytest.raises(ValueError):
        extract.python_enum("class ErrorLevel(StrEnum):\n    pass\n", "ErrorLevel")
    with pytest.raises(ValueError):
        extract.migrated_viz_types("class Other:\n    pass\n")
    with pytest.raises(ValueError, match="LabelType"):  # values became strings: not a numeric enum any more
        extract.numeric_enum("export enum LabelType {\n  Key = 'key',\n}\n", "LabelType")
    with pytest.raises(ValueError, match="sortAxisChoices"):
        extract.array_choices(double_quotes, "sortAxisChoices")
