"""Independent frontend query references for the public example charts.

Generated by bin/scripts/extract_example_query_contexts.py, never by the library's query builder.
Only instance identifiers are rebound when replaying a capture against another test stack.
"""
import copy
import hashlib
import json


INSTANCE_FIELDS = {"datasource", "slice_id", "dashboards", "url_params", "dashboardId"}


def portable(value):
    """Drop dataset column ids and Explore session parameters from a captured structure."""
    if isinstance(value, list):
        return [portable(item) for item in value]
    if isinstance(value, dict):
        return {key: portable(item) for key, item in value.items()
                if key != "url_params" and not (key == "id" and "column_name" in value)}
    return value


def params_fingerprint(source: dict) -> str:
    """Detect edited example params without depending on ids assigned by load_examples."""
    params = json.loads(source["params"]) if isinstance(source["params"], str) else source["params"]
    params = portable({key: value for key, value in params.items() if key not in INSTANCE_FIELDS})
    return hashlib.sha256(json.dumps(params, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def reference_context(source: dict, captures: dict) -> dict:
    """Replay this exact chart's frontend query; missing or stale captures fail, with no builder fallback."""
    identity = f"{source['slice_name']!r} ({source['uuid']})"
    assert source["uuid"] in captures, f"No frontend query capture for {identity}; regenerate the example captures"
    entry = captures[source["uuid"]]
    assert (entry["slice_name"], entry["viz_type"], entry["params_sha256"]) == (
        source["slice_name"], source["viz_type"], params_fingerprint(source)
    ), f"Stale frontend query capture for {identity}; regenerate the example captures"
    context = copy.deepcopy(entry["query_context"])
    context["datasource"] = {"id": source["datasource_id"], "type": source["datasource_type"]}
    # Replaying a slice_id would make ChartDataRestApi overwrite the original's stored query_context.
    context["form_data"]["datasource"] = f"{source['datasource_id']}__{source['datasource_type']}"
    return context
